/**
 * 通知域：站内通知的异步扇出与投递。
 *
 * <p>本模块是纯消费方——自己不产生业务事件，只订阅
 * {@code forum.like} / {@code forum.comment} 等主题，扇出成给具体用户的通知记录。
 * 把它独立成模块的理由是：通知是典型的「可延迟、可丢失、可降级」业务，
 * 在大促或秒杀期间应当能整体降级而不影响主链路，
 * 独立模块才便于做这种隔离。
 *
 * <p><b>扇出的两个放大效应要特别注意：</b>
 * <ul>
 *   <li>一条「被点赞」事件只产生一条通知，但如果帖子作者有几万粉丝、
 *       且业务要求「关注的人发帖也通知」，一条事件就会扇出几万条写入——
 *       这类放大必须在消费侧限流，否则会把通知表写爆。</li>
 *   <li>本模块消费的是「至少一次」投递的消息，同一条事件可能被处理多次，
 *       因此通知去重不能只靠 Redis（有 TTL），
 *       最终要落在 {@code t_notification} 的
 *       {@code (user_id, type, biz_id)} 唯一索引上。</li>
 * </ul>
 *
 * <p>包结构与模块约定见 {@code com.school.forum.user} 的 package-info。
 */
package com.school.forum.notification;
