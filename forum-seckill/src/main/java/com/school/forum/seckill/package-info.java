/**
 * 营销域：优惠券、秒杀活动、库存预扣减、订单。
 *
 * <p><b>秒杀主链路（目标是 10000 QPS、P99 &lt; 50ms、超卖 0 件）：</b>
 * <pre>
 *   1. 请求进 Redis，用 Lua 脚本原子完成「查库存 → 查限购 → 扣库存 → 记录购买人」
 *      —— 四步在一次 Lua 执行里完成，中间不可能被其他请求插入
 *   2. Lua 返回成功的请求，投递一条下单消息到 MQ，然后<b>立刻返回</b>
 *      —— 用户不需要等订单落库
 *   3. 消费端异步落库：扣 MySQL 库存 + 生成订单
 *   4. 前端拿 requestId 轮询查询结果
 * </pre>
 *
 * <p><b>为什么用 Lua 而不是 Redisson 分布式锁：</b>
 * 锁的语义是「串行化」，10000 QPS 下排队等待会直接把 P99 拉到几百毫秒；
 * 而 Lua 脚本在 Redis 单线程内原子执行，没有排队开销。
 * 锁更适合「同一活动的运营操作」这种低频场景（如手动补库存），
 * 不适合挡用户请求。
 *
 * <p><b>防超卖是五层而不是一层：</b>
 * Redis Lua 预扣减只是第一层，后面还有 MySQL 条件更新、唯一索引、
 * 库存三层模型（{@code total = available + locked + sold}）的对账校验。
 * 任何一层单独失效都不会造成超卖——分布式系统的正确性不能建立在
 * 「某个组件一定不出问题」的假设上。
 *
 * <p>包结构与模块约定见 {@code com.school.forum.user} 的 package-info。
 */
