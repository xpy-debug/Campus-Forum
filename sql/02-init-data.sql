-- 11. 收敛冗余计数
-- 生产环境中这些字段由 MQ 消费者异步维护；此处手动同步，使种子数据自洽，
-- 以便直接验证《04-数据库设计》中的对账查询：
--   SELECT COUNT(*) FROM t_user_like WHERE target_type=1 AND target_id=?;
--   应等于 t_post.like_count。
--
-- 注意：必须放在 t_user_like / t_comment / t_post 全部插入之后执行。
-- -------------------------------------------------------------------------------------

-- 11.1 帖子评论数（自 t_comment 聚合）
UPDATE `t_post` p
SET p.`comment_count` = (SELECT COUNT(*)
                         FROM `t_comment` c
                         WHERE c.`post_id` = p.`id`
                           AND c.`status` = 1);

-- 11.2 帖子点赞数（自 t_user_like 聚合）
UPDATE `t_post` p
SET p.`like_count` = (SELECT COUNT(*)
                      FROM `t_user_like` l
                      WHERE l.`target_type` = 1
                        AND l.`target_id` = p.`id`);

-- 11.3 评论点赞数（自 t_user_like 聚合）
UPDATE `t_comment` c
SET c.`like_count` = (SELECT COUNT(*)
                      FROM `t_user_like` l
                      WHERE l.`target_type` = 2
                        AND l.`target_id` = c.`id`);

-- 11.4 一级评论的子回复数
-- 【注意】不能写成 SET c.reply_count = (SELECT COUNT(*) FROM t_comment r WHERE r.root_id = c.id)，
-- MySQL 会报 ERROR 1093（不能在 UPDATE 的子查询中引用被更新的表），
-- 必须先用派生表物化聚合结果，再 JOIN 回写。
UPDATE `t_comment` c
    JOIN (SELECT `root_id`, COUNT(*) AS cnt
          FROM `t_comment`
          WHERE `root_id` > 0
            AND `status` = 1
          GROUP BY `root_id`) agg
    ON agg.`root_id` = c.`id`
SET c.`reply_count` = agg.cnt
WHERE c.`level` = 1;

-- 11.5 标签引用次数
UPDATE `t_tag` t
SET t.`use_count` = (SELECT COUNT(*) FROM `t_post_tag` pt WHERE pt.`tag_id` = t.`id`);

-- 11.6 热度分
-- 公式：(点赞*2 + 评论*3 + 收藏*4) / (发帖至今小时数 + 2)
-- 生产环境由每 5 分钟的定时任务批量重算，此处按同一公式初始化。
UPDATE `t_post` p
SET p.`hot_score` = ROUND(
        (p.`like_count` * 2 + p.`comment_count` * 3 + p.`collect_count` * 4)
            / (TIMESTAMPDIFF(HOUR, p.`publish_time`, NOW()) + 2)
    , 4);

