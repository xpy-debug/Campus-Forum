/**
 * 积分与商城域：每日签到、月度全勤奖励、积分账户与流水、积分商城兑换。
 *
 * <p>本模块的两条链路在设计上是刻意相反的，容易混淆，因此在这里写清楚：
 *
 * <ul>
 *   <li><b>签到：Redis 位图在前，MySQL 在后。</b>位图用 {@code SETBIT} 的返回值
 *       一次性完成「判重 + 写入」，把每次签到压到一次 Redis 往返；
 *       {@code t_user_signin} 仍是最终真相，位图只是可重建的加速器，
 *       由每日任务从签到记录重建（ADR-007）。</li>
 *   <li><b>兑换：不引入 Redis 库存预扣，直接条件更新 MySQL。</b>
 *       商城的并发量级与秒杀完全不同，预扣只会凭空多出一份需要同步的状态，
 *       而失败路径还要处理「Redis 扣了但订单没建」（ADR-008）。</li>
 * </ul>
 *
 * <p>共同点是<b>全同步</b>：两条链路都不发消息。签到要立刻告诉用户「+5 分」，
 * 兑换要立刻扣掉积分并生成订单，任何异步化都会引入用户能感知的中间态。
 * 因此本模块不依赖任何 MQ 客户端——这既是业务选择，也让 ArchUnit 的
 * 「业务模块不得依赖 MQ 客户端」规则在这里天然成立。
 *
 * <p>包结构与模块约定见 {@code com.school.forum.user} 的 package-info。
 *
 * <p><b>权限边界</b>：用户侧只有 {@code controller} 下的浏览与下单接口，
 * 改商品、发货、结算奖励等管理能力全部通过 {@code api} 包暴露给
 * {@code forum-admin}，由 {@code @RequireRole} 在拦截器层拦截（ADR-009）。
 * 本模块内部不做权限判断——权限是「谁能进来」的问题，不是「进来之后做什么」的问题。
 */
